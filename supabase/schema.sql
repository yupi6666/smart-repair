-- 智能报修小助手 · Supabase 建表脚本
-- 使用方式：Supabase 控制台 → SQL Editor → New query → 粘贴整段 → Run

create table if not exists tickets (
  id bigint generated by default as identity primary key,
  name text not null,
  area text not null,
  device_type text not null,
  description text not null,
  status text not null default '待处理',
  suggestions jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

-- 开启行级安全
alter table tickets enable row level security;

-- 允许匿名读取工单
create policy "tickets_select_anon" on tickets
  for select to anon using (true);

-- 允许匿名创建工单
create policy "tickets_insert_anon" on tickets
  for insert to anon with check (true);

-- 允许匿名更新状态/AI 建议
create policy "tickets_update_anon" on tickets
  for update to anon using (true) with check (true);
